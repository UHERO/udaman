  MODIFY `role` ENUM('external','fsonly','internal','fellow','admin','dev') NOT NULL DEFAULT 'external';

ALTER TABLE `role_permissions`
  MODIFY `role` ENUM('external','fsonly','internal','fellow','admin','dev') NOT NULL;

