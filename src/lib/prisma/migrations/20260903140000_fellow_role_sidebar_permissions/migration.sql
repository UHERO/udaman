-- Fellow role + per-sidebar-item CRUD permissions (2026-09-03)
--
-- 1. Adds the `fellow` role to the users/role_permissions enums. Fellows get
--    the Housing Database, Comms, and Registry apps by default; their
--    server-side access is governed entirely by role_permissions.
-- 2. Seeds one row per (role, top-level sidebar item, CRUD action) so the
--    admin Permissions page can show a full matrix. The resource names match
--    `resource:` on each ROUTES entry in src/lib/auth/route-access.ts.
--    Fine-grained resources checked by server actions (category, worker,
--    ...) roll up to these via RESOURCE_PARENTS in src/lib/auth/resources.ts.
--
-- Defaults establish the post-lockdown baseline, so existing rows for these
-- exact (role, resource, action) keys are overwritten. Wildcard rows (`*`)
-- are left alone; they only apply where no sidebar-level row matches.

