/** County digit for a ZIP (5-digit or ZIP+4), or null when unknown. */
export function zipCounty(zip: string | null | undefined): string | null {
  const z = /^\s*(\d{5})/.exec(zip ?? "")?.[1];
  if (!z) return null;
  return ZIP_COUNTY[z] ?? (z.startsWith("968") ? "1" : null);
}
