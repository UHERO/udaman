describe("Denton (1971) table p.101", () => {
  for (const criterion of ["additive", "proportional"] as const) {
    for (const h of [0, 1, 2, 3]) {
      it(`${criterion}, h=${h}`, () => {
        const r = disaggregate(dA, {
          ratio: 4,
          method: "denton",
          indicator: dQ,
          criterion,
          h,
          conversion: "sum",
        });
        expect(r.values.length).toBe(20);
        const ref = REFERENCE[`${criterion}-${h}` as keyof typeof REFERENCE];
        r.values.forEach((v, i) => {
          expect(Math.abs(v - ref[i])).toBeLessThanOrEqual(
            1e-10 * (1 + Math.abs(ref[i])),
          );
        });
        const agg = aggregate(r.values, { ratio: 4, conversion: "sum" });
        agg.forEach((v, i) =>
          expect(Math.abs(v - dA[i])).toBeLessThan(1e-9 * dA[i]),
        );
      });
    }
  }
});
